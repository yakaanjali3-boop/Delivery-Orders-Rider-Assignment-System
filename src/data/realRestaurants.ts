/**
 * Filter real restaurants strictly by city name.
 * Never mixes restaurants from different cities.
 */
export function getRestaurantsByCity(city: string): RealRestaurant[] {
  if (!city) return [];
  const normalized = city.trim().toLowerCase();
  return REAL_RESTAURANTS.filter((r) => r.city.toLowerCase() === normalized);
}

/**
 * Returns all supported Indian cities list.
 */
export function getAllCities(): string[] {
  return [...INDIAN_CITIES];
}
